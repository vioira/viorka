func TestOpenAPIExportAndPublicDocuments(t *testing.T) {
	doc := OpenAPIDocument()
	yaml, err := doc.YAML()
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile("../../api/openapi/openapi.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(committed, append([]byte("# Code generated by go run ./cmd/openapi; DO NOT EDIT.\n"), yaml...)) {
		t.Fatal("OpenAPI is stale; run make generate-openapi")
	}
	// No application dependencies are needed to serve the public contract.
	router := NewRouter(Dependencies{})
	for _, tc := range []struct{ path, contentType, contains string }{
		{"/docs", "text/html", `spec-url="/openapi.json"`},
		{"/openapi.json", "application/json", `"openapi":"3.1.0"`},
		{"/openapi.yaml", "application/yaml", "openapi: 3.1.0"},
	} {
		t.Run(tc.path, func(t *testing.T) {
			w := httptest.NewRecorder()
			router.ServeHTTP(w, httptest.NewRequest("GET", tc.path, nil))
			if w.Code != 200 || !strings.Contains(w.Header().Get("Content-Type"), tc.contentType) || !strings.Contains(w.Body.String(), tc.contains) {
				t.Fatalf("unexpected document: %d %s", w.Code, w.Body.String())
			}
			if tc.path == "/openapi.yaml" && !bytes.Equal(w.Body.Bytes(), yaml) {
				t.Fatal("live document differs from export")
			}
			if tc.path == "/openapi.json" {
				var value map[string]any
				if err := json.Unmarshal(w.Body.Bytes(), &value); err != nil {
					t.Fatal(err)
				}
				user := value["components"].(map[string]any)["schemas"].(map[string]any)["User"].(map[string]any)
				if _, ok := user["properties"].(map[string]any)["password_hash"]; ok {
					t.Fatal("password hash exposed in schema")
				}
			}
		})
	}
}

func TestHTTPResponsesMatchGeneratedContract(t *testing.T) {
	f := setup(t, "admin")
	node, _ := f.enroll()
	doc := OpenAPIDocument()
	for _, tc := range []struct {
		method, path, specPath string
		body                   any
		authenticated          bool
		status                 int
	}{
		{"GET", "/healthz", "/healthz", nil, false, 200},
		{"GET", "/readyz", "/readyz", nil, false, 200},
		{"GET", "/api/v1/version", "/api/v1/version", nil, false, 200},
		{"GET", "/api/v1/auth/session", "/api/v1/auth/session", nil, true, 200},
		{"GET", "/api/v1/auth/session", "/api/v1/auth/session", nil, false, 401},
		{"GET", "/api/v1/nodes", "/api/v1/nodes", nil, true, 200},
		{"GET", "/api/v1/nodes?limit=101", "/api/v1/nodes", nil, true, 400},
		{"POST", "/api/v1/enrollment-tokens", "/api/v1/enrollment-tokens", EnrollmentRequest{Name: "test", Kind: "nat"}, true, 201},
		{"POST", "/api/v1/enrollment-tokens", "/api/v1/enrollment-tokens", map[string]string{"name": "test", "kind": "nat", "extra": "rejected"}, true, 400},
		{"POST", "/api/v1/nodes/" + node + "/tasks", "/api/v1/nodes/{id}/tasks", TaskRequest{Operation: "node.inspect", IdempotencyKey: "contract"}, true, 202},
		{"POST", "/api/v1/agents/challenge", "/api/v1/agents/challenge", ChallengeRequest{NodeID: node}, false, 200},
	} {
		t.Run(tc.method+tc.path+strconv.Itoa(tc.status), func(t *testing.T) {
			response := f.request(tc.method, tc.path, tc.body, tc.authenticated)
			defer response.Body.Close()
			if response.StatusCode != tc.status {
				t.Fatalf("status %d, want %d", response.StatusCode, tc.status)
			}
			path := doc.Paths[tc.specPath]
			op := path.Get
			if tc.method == http.MethodPost {
				op = path.Post
			}
			declared := op.Responses[strconv.Itoa(response.StatusCode)]
			if declared == nil {
				t.Fatalf("undocumented status %d", response.StatusCode)
			}
			var value any
			if err := json.NewDecoder(response.Body).Decode(&value); err != nil {
				t.Fatal(err)
			}
			result := &huma.ValidateResult{}
			huma.Validate(doc.Components.Schemas, declared.Content["application/json"].Schema, &huma.PathBuffer{}, huma.ModeReadFromServer, value, result)
			if len(result.Errors) != 0 {
				t.Fatalf("response violates generated schema: %v", result.Errors)
			}
		})
	}
}

func TestStreamingAndSecurityContracts(t *testing.T) {
	doc := OpenAPIDocument()
	ws := doc.Paths["/api/v1/agents/ws"].Get
	if _, ok := ws.Security[0]["agentBearer"]; !ok || ws.Responses["101"] == nil {
		t.Fatal("missing WebSocket handshake contract")
	}
	events := doc.Paths["/api/v1/events"].Get
	if events.Responses["200"].Content["text/event-stream"] == nil {
		t.Fatal("missing SSE media type")
	}
	task := doc.Paths["/api/v1/nodes/{id}/tasks"].Post
	if _, ok := task.Security[0]["cookieAuth"]; !ok {
		t.Fatal("missing cookie security")
	}
	found := map[string]bool{}
	for _, p := range task.Parameters {
		if p.Required {
			found[p.Name] = true
		}
	}
	for _, name := range []string{"id", "Origin", "X-CSRF-Token"} {
		if !found[name] {
			t.Fatalf("missing required %s", name)
		}
	}
	if task.Responses["202"] == nil || task.Responses["200"] != nil {
		t.Fatal("task must document acceptance, not completion")
	}
}
