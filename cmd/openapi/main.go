// Command openapi exports the API contract without starting the application.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"

	"github.com/vioira/viorka/internal/httpapi"
)

func main() {
	check := flag.Bool("check", false, "fail if the generated document differs from the committed file")
	output := flag.String("output", "api/openapi/openapi.yaml", "output path")
	flag.Parse()
	b, err := httpapi.OpenAPIDocument().YAML()
	if err == nil {
		b = append([]byte("# Code generated by go run ./cmd/openapi; DO NOT EDIT.\n"), b...)
		if *check {
			var current []byte
			current, err = os.ReadFile(*output)
			if err == nil && !bytes.Equal(current, b) {
				err = fmt.Errorf("OpenAPI is stale; run make generate-openapi")
			}
		} else {
			err = os.WriteFile(*output, b, 0644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
